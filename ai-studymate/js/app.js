/* ---- Mobile hamburger menu ---- */
(function setupNav() {
  const hamburger = document.getElementById('nav-hamburger');
  const navLinks  = document.getElementById('nav-links');
  if (!hamburger || !navLinks) return;
  hamburger.addEventListener('click', () => {
    navLinks.classList.toggle('open');
    hamburger.setAttribute('aria-expanded', navLinks.classList.contains('open'));
  });
  // close on link click
  navLinks.querySelectorAll('a').forEach(a => {
    a.addEventListener('click', () => navLinks.classList.remove('open'));
  });
})();

/* ---- Sidebar active state ---- */
(function setSidebarActive() {
  const page = window.location.pathname.split('/').pop();
  document.querySelectorAll('.sidebar__link').forEach(link => {
    const href = link.getAttribute('href');
    if (href && href.split('/').pop() === page) {
      link.classList.add('active');
    }
  });
})();

/* ---- Tab switching ---- */
function initTabs(container) {
  const tabs   = container.querySelectorAll('.tab');
  const panels = container.querySelectorAll('.tab-panel');
  tabs.forEach(tab => {
    tab.addEventListener('click', () => {
      tabs.forEach(t   => t.classList.remove('active'));
      panels.forEach(p => p.classList.remove('active'));
      tab.classList.add('active');
      const target = document.getElementById(tab.dataset.target);
      if (target) target.classList.add('active');
    });
  });
  // activate first tab
  if (tabs.length) tabs[0].click();
}
document.querySelectorAll('[data-tabs]').forEach(initTabs);

/* ---- Settings modal ---- */
(function setupSettings() {
  const trigger = document.getElementById('settings-btn');
  const modal   = document.getElementById('settings-modal');
  const overlay = document.getElementById('settings-overlay');
  const closeBtn= document.getElementById('settings-close');
  const form    = document.getElementById('settings-form');
  const keyInput= document.getElementById('api-key-input');
  const saved   = document.getElementById('settings-saved');
  if (!trigger || !modal) return;

  function open() {
    modal.hidden = false;
    overlay.hidden = false;
    if (keyInput) keyInput.value = getApiKey() ? '••••••••••••' + getApiKey().slice(-4) : '';
  }
  function close() {
    modal.hidden = true;
    overlay.hidden = true;
  }
  trigger.addEventListener('click', open);
  if (closeBtn)  closeBtn.addEventListener('click', close);
  if (overlay)   overlay.addEventListener('click', close);

  if (form) {
    form.addEventListener('submit', e => {
      e.preventDefault();
      const raw = keyInput.value.trim();
      if (raw && !raw.startsWith('•')) saveApiKey(raw);
      if (saved) {
        saved.style.display = 'inline';
        setTimeout(() => { saved.style.display = 'none'; }, 2000);
      }
      close();
      refreshAiBanner();
    });
  }
})();

/* ---- AI demo banner ---- */
function refreshAiBanner() {
  const banner = document.getElementById('ai-status-banner');
  if (!banner) return;
  const hasKey = !!getApiKey();
  banner.className = 'ai-banner' + (hasKey ? ' ai-banner--live' : '');
  banner.innerHTML = hasKey
    ? '✅ <strong>Live AI active</strong> — responses are generated by OpenAI in real time.'
    : '🎓 <strong>Demo Mode</strong> — Running with rich sample content. No API key required. <a href="#" id="open-settings-from-banner">Add key for Live AI →</a>';
  const link = document.getElementById('open-settings-from-banner');
  if (link) link.addEventListener('click', e => {
    e.preventDefault();
    document.getElementById('settings-btn')?.click();
  });
}
document.addEventListener('DOMContentLoaded', refreshAiBanner);

/* ---- Show an API error toast above the result ---- */
function showErrorMessage(containerEl, message) {
  if (!containerEl) return;
  // Remove any previous error toast
  const prev = containerEl.querySelector('.api-error-toast');
  if (prev) prev.remove();

  const toast = document.createElement('div');
  toast.className = 'api-error-toast';
  toast.innerHTML = `<strong>API Error</strong> — ${message}
    <br><small>Demo Mode content is shown below so you can still use all features.</small>`;
  containerEl.insertBefore(toast, containerEl.firstChild);
}

/* ---- Generic loading state helper ---- */
function setLoading(btn, resultEl, isLoading, loadingText = 'Generating…') {
  if (isLoading) {
    btn.disabled = true;
    btn._origHTML = btn.innerHTML;
    btn.innerHTML = `<span class="spinner"></span> ${loadingText}`;
    if (resultEl) resultEl.innerHTML = '';
  } else {
    btn.disabled = false;
    btn.innerHTML = btn._origHTML || 'Generate';
  }
}

/* ---- Render result text with optional demo watermark ---- */
function renderResult(el, text, isDemo = false) {
  if (!el) return;
  el.className = 'result-box' + (isDemo ? ' result-box--demo' : ' result-box--live');
  el.textContent = text;
}

function renderEmpty(el, msg = 'Results will appear here.') {
  if (!el) return;
  el.className = 'result-box result-box--empty';
  el.textContent = msg;
}
